// Execute com UNSPLASH_ACCESS_KEY no ambiente. Somente metadados públicos são gravados.
const fs = require('node:fs');
const vm = require('node:vm');
const topics = require('./unsplash-topics.cjs');
const output = 'public/unsplash-photos.js';
const context = {window:{}};
vm.runInNewContext(fs.readFileSync('public/lessons.js','utf8'), context);
const lessons = context.window.NEXO_LESSONS;
const pools = {};
if (fs.existsSync(output)) {
  vm.runInNewContext(fs.readFileSync(output,'utf8'), context);
  for (const row of context.window.NEXO_UNSPLASH_PHOTOS || [])
    for (const entry of row) if (entry?.photos?.length) pools[entry.query] = entry.photos;
}
function save() {
  const rows = topics.map((row,s)=>row.map((query,t)=>({title:lessons[s][t].title,query,photos:pools[query]||[]})));
  fs.writeFileSync(output, '// Generated by scripts/generate-unsplash.cjs; public photo metadata only.\nwindow.NEXO_UNSPLASH_PHOTOS = '+JSON.stringify(rows,null,2)+';\n');
}
async function main() {
  if (!process.env.UNSPLASH_ACCESS_KEY) throw Error('Configure UNSPLASH_ACCESS_KEY no ambiente.');
  for (const query of new Set(topics.flat())) {
    if (pools[query]?.length && !process.argv.includes('--refresh')) continue;
    const url = new URL('https://api.unsplash.com/search/photos');
    url.search = new URLSearchParams({query,per_page:'3',orientation:'landscape',content_filter:'high'});
    const response = await fetch(url,{headers:{Authorization:'Client-ID '+process.env.UNSPLASH_ACCESS_KEY,'Accept-Version':'v1'},signal:AbortSignal.timeout(20000)});
    if (!response.ok) throw Error('Unsplash HTTP '+response.status+'; execute novamente para retomar do cache.');
    const body = await response.json();
    if (!body.results?.length) throw Error('Sem fotografias para '+query);
    pools[query] = body.results.map(p=>({id:p.id,url:p.urls.regular,photographer:p.user.name,profile:p.user.links.html,page:p.links.html}));
    save();
    console.log('OK: '+query);
  }
  save();
  console.log('77 lições cobertas; '+Object.keys(pools).length+' consultas reutilizadas nos questionários.');
}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
